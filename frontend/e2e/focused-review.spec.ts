test('真实本地 Git：选择决策树、等待完成、打开提交详情和刷新', async ({ page }, info) => {
  test.setTimeout(180000)
  // The disposable local Git source is registered through the API; public forms remain HTTP(S)-only.
  const created = await page.request.post('/api/v1/repositories', { data: { repositoryUrl: REPOSITORY.replaceAll('\\', '/') } })
  expect(created.ok()).toBe(true)
  const project = await created.json()
  await page.goto(`/#/projects/${project.repositoryId}`)
  await page.getByRole('button', { name: /分析选项/ }).click()
  await page.getByLabel('起始日期', { exact: true }).fill('2024-01-01')
  await page.getByLabel('结束日期', { exact: true }).fill('2024-01-08')
  await page.getByLabel('提交上限', { exact: true }).fill(info.project.name === 'desktop-1280' ? '431' : '432')
  const modelChoices = await (await page.request.get('/api/v1/repository-models')).json()
  const tree = modelChoices.models.find((model: { method: string }) => model.method === 'decision-tree-v1')
  expect(tree).toBeTruthy()
  await page.getByLabel('分析模型', { exact: true }).selectOption(tree.modelId)
  const posted = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/v1/repository-syncs'))
  await page.getByRole('button', { name: '开始分析', exact: true }).click()
  const job = await (await posted).json()
  expect(job.requestedModelId).toBe(tree.modelId)
  const record = page.getByRole('article', { name: `分析记录 ${job.syncId}`, exact: true })
  await expect(record.getByRole('button', { name: '打开结果', exact: true })).toBeVisible({ timeout: 120000 })
  const actual = await (await page.request.get(`/api/v1/repository-syncs/${job.syncId}`)).json()
  expect(actual.modelId).toBe(tree.modelId)
  await record.getByRole('button', { name: '打开结果', exact: true }).click()
  const first = page.getByRole('button', { name: /^查看 [a-f0-9]{40}$/ }).first()
  await expect(first).toBeVisible()
  const sha = (await first.getAttribute('title'))!
  await first.click()
  const detail = page.getByRole('dialog', { name: '提交详情' })
  await expect(detail).toBeVisible()
  await expect(detail.getByText('模型分数', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(detail).not.toBeVisible()
  await expect(page.getByRole('button', { name: `查看 ${sha}` })).toBeVisible()
  const pinned = page.url()
  await page.reload()
  await expect(page).toHaveURL(pinned)
  await expect(page.getByRole('button', { name: `查看 ${sha}` })).toBeVisible()
  await noOverflow(page)
  await page.screenshot({ path: `${ensureDir(runScreenshotDir)}/review-${info.project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: /^返回项目 / }).click()
  await expect(page).toHaveURL(new RegExp(`/projects/${project.repositoryId}$`))
  if (!await record.getByRole('radio').isChecked()) await record.getByRole('radio').click()
  await expect(record.getByRole('radio')).toBeChecked()
  await expect(page.getByRole('region', { name: '当前分析结果', exact: true }).getByText(tree.name, { exact: true })).toBeVisible({ timeout: catalogTimeout })
  await page.setViewportSize({ width: 390, height: 844 })
  await noOverflow(page)
  await page.screenshot({ path: `${ensureDir(runScreenshotDir)}/project-narrow-${info.project.name}.png`, fullPage: true })
})

test('九种模型都实际用于仓库分析', async ({ page }, info) => {
  test.setTimeout(180000)
  const response = await page.request.post('/api/v1/repositories', { data: { repositoryUrl: REPOSITORY.replaceAll('\\', '/') } })
  const project = await response.json()
  const choices = await (await page.request.get('/api/v1/repository-models')).json()
  await page.goto(`/#/projects/${project.repositoryId}`)
  await page.getByRole('button', { name: /分析选项/ }).click()
  await page.getByLabel('起始日期', { exact: true }).fill('2024-01-01')
  await page.getByLabel('结束日期', { exact: true }).fill('2024-01-08')
  await page.getByLabel('提交上限', { exact: true }).fill(info.project.name === 'desktop-1280' ? '421' : '422')
  expect(choices.models).toHaveLength(9)
  for (const model of choices.models) {
    expect(model?.repositoryPredictionSupported).toBe(true)
    await page.getByLabel('分析模型', { exact: true }).selectOption(model.modelId)
    const posted = page.waitForResponse(result => result.request().method() === 'POST' && result.url().endsWith('/api/v1/repository-syncs'))
    await page.getByRole('button', { name: '开始分析', exact: true }).click()
    const job = await (await posted).json()
    expect(job.requestedModelId).toBe(model.modelId)
    await expect(page.getByRole('article', { name: `分析记录 ${job.syncId}`, exact: true }).getByRole('button', { name: '打开结果', exact: true })).toBeVisible({ timeout: 120000 })
    const actual = await (await page.request.get(`/api/v1/repository-syncs/${job.syncId}`)).json()
    expect(actual.modelId).toBe(model.modelId)
  }
})

test('管理员登录、模型产物登记、验证报告和退出权限', async ({ page }, info) => {
  await adminSession(page)
  await page.request.post('/api/admin/logout')
  await page.goto('/#/admin')
  await expect(page.getByRole('heading', { name: '管理员登录', exact: true })).toBeVisible()
  await page.getByLabel('管理员账户名').fill(account.username)
  await page.getByLabel('管理员密码', { exact: true }).fill(account.password)
  await page.getByRole('button', { name: '登录管理工作区' }).click()
  await expect(page.getByRole('heading', { name: '模型管理', exact: true })).toBeVisible()
  await expect(page.locator('.admin-model-card')).toHaveCount(9, { timeout: catalogTimeout })
  await page.getByRole('button', { name: '校验并登记', exact: true }).first().click()
  await expect(page.getByRole('status').filter({ hasText: '产物校验通过' })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: `${ensureDir(runScreenshotDir)}/admin-models-${info.project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: '数据记录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '数据记录', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '模型管理', exact: true }).click()
  await page.getByRole('button', { name: '验证报告', exact: true }).click()
  await expect(page.getByRole('heading', { name: '验证报告', exact: true })).toBeVisible()
  await expect(page.getByText('一份可核对的模型验证')).toBeVisible()
  await page.getByRole('button', { name: '退出管理', exact: true }).click()
  await expect(page.getByRole('heading', { name: '管理员登录', exact: true })).toBeVisible()
  expect((await page.request.get('/api/v1/models')).status()).toBe(401)
  await expect(page.locator('.admin-model-card')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: '管理工作区', exact: true })).toBeVisible()
  await noOverflow(page)
})

