test('验证报告单一标题、真实运行与缺聚合反馈', async ({ page }) => {
  await page.goto('/#/reports')
  await expect(page.getByRole('heading', { name: '验证报告', exact: true })).toBeVisible()
  await expect(page.getByText('公开历史数据', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '提交记录', exact: true }).click()
  await expect(page.getByRole('button', { name: /^查看 [a-f0-9]{40}$/ }).first()).toBeVisible()
  const run = page.url().split('/reports/')[1].split('/')[0]
  await page.getByRole('button', { name: '时间趋势', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/reports/${run}/trends$`))
  await expect(page.locator('h1')).toHaveCount(1)
  await expect(page.getByRole('region', { name: '历史趋势图', exact: true }).or(page.getByText('该运行未提供趋势聚合'))).toBeVisible()
  const drill = page.getByRole('button', { name: /^查看该桶提交/ }).first()
  if (await drill.count()) { await drill.click(); await expect(page.getByLabel('起始日期')).not.toHaveValue(''); expect(page.url()).toContain(`/reports/${run}/commits`) }
  else await expect(page.getByText('该运行未提供趋势聚合')).toBeVisible()
  await noOverflow(page)
})
test('项目读取失败可以重试，空集合不会冒充故障', async ({ page }) => {
  let failed = true
  await page.route('**/api/v1/repositories?*', route => route.fulfill({ status: failed ? 503 : 200, contentType: 'application/json', body: JSON.stringify(failed ? { error: { code: 'STORAGE_UNAVAILABLE', message: '目录暂不可读', requestId: 'fixture-retry' } } : { repositories: [], total: 0, offset: 0, limit: 100 }) }))
  await page.goto('/#/projects')
  await expect(page.getByRole('heading', { name: '项目读取失败' })).toBeVisible()
  failed = false
  await page.getByRole('button', { name: '重新加载' }).click()
  await expect(page.getByRole('heading', { name: '从一个仓库开始' })).toBeVisible()
  await noOverflow(page)
})
