test('外观为轻量控件，首帧/键盘/reduced-motion 与本地资源保持', async ({ page }) => {
  const external: string[] = []
  page.on('request', request => { if (!new URL(request.url()).hostname.match(/^(127\.0\.0\.1|localhost)$/)) external.push(request.url()) })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#/projects')
  await page.getByRole('button', { name: '外观偏好' }).click()
  await page.getByRole('button', { name: '深色', exact: true }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'charcoal')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: '跳到主要内容' })).toBeFocused()
  expect(external).toEqual([])
  await page.getByRole('button', { name: '外观偏好' }).click()
  await page.getByRole('button', { name: '浅色', exact: true }).click()
  await noOverflow(page)
})

test('键盘可展开分析选项、提交真实任务并打开和关闭详情', async ({ page }) => {
  test.setTimeout(180_000)
  await page.goto('/#/connect')
  await page.getByLabel('仓库地址', { exact: true }).focus()
  await page.keyboard.type(REPOSITORY.replaceAll('\\', '/'))
  await page.keyboard.press('Tab')
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('分支', { exact: true })).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('分支', { exact: true })).toBeFocused()
  await page.getByLabel('起始日期', { exact: true }).fill('2024-01-01')
  await page.getByLabel('结束日期', { exact: true }).fill('2024-01-08')
  const posted = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/v1/repository-syncs'))
  await page.getByRole('button', { name: '开始分析' }).focus()
  await page.keyboard.press('Enter')
  const job = await (await posted).json()
  const open = page.getByRole('article', { name: `分析任务 ${job.syncId}` }).getByRole('button', { name: '查看结果' })
  await expect(open).toBeVisible({ timeout: 120_000 })
  await open.focus(); await page.keyboard.press('Enter')
  const row = page.getByRole('button', { name: /^查看 [a-f0-9]{40}$/ }).first()
  await row.focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog', { name: '提交详情' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(row).toBeFocused()
})
