import { test, expect, type Page } from '@playwright/test'
import { REPOSITORY } from './repository-setup.ts'
import { ensureDir, runScreenshotDir } from '../evidence.ts'

async function noOverflow(page: Page) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true) }
test('首屏直接读取项目，只展示项目与验证报告', async ({ page }) => {
  const protectedHeaders: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) { const value = request.headers()['authorization']; if (value) protectedHeaders.push(value) } })
  await page.goto('/#/projects')
  await expect(page.getByRole('heading', { name: '项目', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '新建分析' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: '主导航' }).getByRole('button')).toHaveCount(2)
  await expect(page.getByText('设置团队连接')).toHaveCount(0)
  expect(protectedHeaders).toEqual([])
  await noOverflow(page)
})
test('真实本地 Git：无凭证接入、固定分析、详情、计划和报告往返', async ({ page }, info) => {
  test.setTimeout(180_000)
  await page.goto('/#/projects')
  await page.getByRole('button', { name: '新建分析' }).click()
  await page.getByLabel('仓库地址', { exact: true }).fill(REPOSITORY.replaceAll('\\', '/'))
  await page.getByText('分析选项', { exact: false }).first().click()
  await page.getByLabel('起始日期', { exact: true }).fill('2024-01-01')
  await page.getByLabel('结束日期', { exact: true }).fill('2024-01-08')
  await page.getByLabel('提交上限').fill(info.project.name === 'desktop-1280' ? '431' : '432')
  const posted = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/v1/repository-syncs'))
  await page.getByRole('button', { name: '开始分析' }).click()
  const job = await (await posted).json()
  const ownJob = page.getByRole('article', { name: `分析任务 ${job.syncId}` })
  await expect(ownJob.getByRole('button', { name: '查看结果' })).toBeVisible({ timeout: 120_000 })
  await ownJob.getByRole('button', { name: '查看结果' }).click()
  await expect(page).toHaveURL(new RegExp(`/analyses/${job.syncId}/commits$`))
  const first = page.getByRole('button', { name: /^查看 [a-f0-9]{40}$/ }).first()
  await expect(first).toBeVisible()
  const sha = (await first.getAttribute('title'))!
  await first.click()
  const detail = page.getByRole('dialog', { name: '提交详情' })
  await expect(detail).toBeVisible()
  await expect(detail).toContainText('E2E')
  await expect(detail.getByText('当前分析未提供逐条模型归因。')).toBeVisible()
  await detail.getByRole('button', { name: '加入审查计划' }).click()
  await page.keyboard.press('Escape')
  await expect(first).toBeFocused()
  await page.getByRole('button', { name: /^审查计划/ }).click()
  await expect(page.getByText('已选 1 条', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: `从计划移除 ${sha}` })).toBeVisible()
  const pinnedPlan = page.url()
  await page.getByRole('button', { name: '验证报告', exact: true }).click()
  await expect(page.getByRole('heading', { name: '验证报告', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'e2e-repo', exact: true }).click()
  await expect(page).toHaveURL(pinnedPlan)
  await page.reload()
  await expect(page.getByRole('button', { name: `从计划移除 ${sha}` })).toBeVisible()
  await page.getByRole('button', { name: /^全部提交/ }).click()
  await expect(page.getByRole('button', { name: `${sha} 已在清单` })).toBeDisabled()
  await expect(page.locator('h1')).toHaveCount(1)
  await noOverflow(page)
  await page.screenshot({ path: `${ensureDir(runScreenshotDir)}/focused-${info.project.name}.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: `查看 ${sha}` }).click()
  await expect(detail).toBeVisible()
  await noOverflow(page)
  await page.screenshot({ path: `${ensureDir(runScreenshotDir)}/focused-narrow-${info.project.name}.png`, fullPage: true })
})
